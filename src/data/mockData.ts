// Helper: Ambil nama hari dari tanggal format YYYY-MM-DD
export function getDayNameFromDate(dateStr: string): BroadcastDay {
  const parts = dateStr.split('-');
  if (parts.length === 3) {
    const d = new Date(parseInt(parts[0], 10), parseInt(parts[1], 10) - 1, parseInt(parts[2], 10));
    const dayIdx = d.getDay();
    const days: BroadcastDay[] = ['Minggu', 'Senin', 'Selasa', 'Rabu', 'Kamis', 'Jumat', 'Sabtu'];
    return days[dayIdx] || 'Senin';
  }
  return 'Senin';
}

// Helper: Bangun deretan mata acara Rundown Harian (Wizard 2) berdasarkan tanggal & blok
export function getPolaAcaraForDateAndBlock(
  dateStr: string,
  block: 'Pagi' | 'Sore'
): RundownProgramRow[] {
  const dayName = getDayNameFromDate(dateStr);
  const dayKey = dayName.toLowerCase() as 'senin' | 'selasa' | 'rabu' | 'kamis' | 'jumat' | 'sabtu' | 'minggu';

  // Filter slots untuk blok terpilih
  // Pagi: jam 06:00:00 s.d. 16:00:00
  // Sore: jam 16:00:00 s.d. 00:00:00
  const slots = OFFICIAL_POLA_GRID_OCTOBER_2026.filter((slot) => {
    const startH = parseInt(slot.jamMulai.split(':')[0], 10);
    if (block === 'Pagi') {
      return startH >= 6 && startH < 16;
    } else {
      return startH >= 16 || startH === 0;
    }
  });

  return slots.map((slot, idx) => {
    const item = slot[dayKey];
    const isRelay = item.category === 'RELAY JAKARTA';
    const isLive = item.category === 'NEWS' && !item.title.includes('RERUN');
    
    // Tentukan kategori sumber broadcast & lokasi studio
    let sourceCategory: 'Live' | 'Relay' | 'Playback' = 'Playback';
    let sumberStr: any = 'Storage 3';
    let lokasiStr = 'Master Control Room (MCR)';

    if (isRelay) {
      sourceCategory = 'Relay';
      sumberStr = 'Relay nasional';
    } else if (isLive) {
      sourceCategory = 'Live';
      sumberStr = 'Live Studio 1';
      lokasiStr = 'Studio 1 (Utama - Live & Berita)';
    } else if (
      item.title.includes('BALIVISION') ||
      item.title.includes('KLIP NAK BALI') ||
      item.title.includes('TETARING') ||
      item.title.includes('DEDALU') ||
      item.title.includes('GEGIRANG')
    ) {
      sumberStr = 'Live Studio 2';
      lokasiStr = 'Studio 2 (Musik & Budaya)';
    } else if (item.title.includes('MIMBAR') || item.title.includes('BAHTERA')) {
      sumberStr = 'Live Studio 3';
      lokasiStr = 'Studio 3 (Podcast & Mimbar Agama)';
    }

    return {
      id: `pola-slot-${slot.id}-${dayKey}-${idx}`,
      mataAcara: item.title,
      tayang: isLive ? 'Live' : (isRelay ? 'Live' : 'Rerun'),
      jamMulai: slot.jamMulai,
      durasi: slot.durasi,
      jamSelesai: slot.jamSelesai,
      sumber: sumberStr,
      sumberCategory: sourceCategory,
      lokasi: lokasiStr,
      catatan: item.notes || `Sesuai Pola Acara TVRI Bali Oktober 2026 (${dayName})`,
      fromPolaAcara: true,
      sisipanList: [],
    };
  });
}
