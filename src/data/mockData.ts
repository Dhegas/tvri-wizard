// Helper: Convert PolaAcaraItem to RundownProgramRow for Wizard 2 Rundown
export function convertPolaToRundownRows(
  items: PolaAcaraItem[]
): RundownProgramRow[] {
  return items.map((p, idx) => ({
    id: `rd-from-pola-${p.id}-${idx}`,
    mataAcara: p.namaProgram,
    tayang: p.isLive ? 'Live' : (p.sumberCategory === 'Relay' ? 'Live' : 'Rerun'),
    jamMulai: p.jamMulai,
    durasi: p.durasi,
    jamSelesai: p.jamSelesai,
    sumber: p.sumber,
    sumberCategory: p.sumberCategory,
    lokasi: p.lokasiStudio,
    catatan: p.deskripsi,
    fromPolaAcara: true,
    sisipanList: p.sisipanDefault || [],
  }));
}

// Helper: Get Pola Acara filtered by day & block
export function getPolaAcaraForBlock(
  day: BroadcastDay | string,
  block: 'Pagi' | 'Sore'
): RundownProgramRow[] {
  const isWeekend = day === 'Sabtu' || day === 'Minggu';

  // Filter items that match day and block
  const matched = MASTER_POLA_ACARA.filter((item) => {
    // Check day match
    const dayMatch =
      item.hari === 'Setiap Hari' ||
      item.hari === day ||
      (!isWeekend && item.hari === 'Senin - Jumat') ||
      (isWeekend && item.hari === 'Sabtu - Minggu');

    if (!dayMatch) return false;

    // Check block match (Pagi = Pagi & Siang; Sore = Sore & Malam)
    if (block === 'Pagi') {
      return item.blok === 'Pagi' || item.blok === 'Siang';
    } else {
      return item.blok === 'Sore' || item.blok === 'Malam';
    }
  });

  return convertPolaToRundownRows(matched);
}

