// Helper to pre-populate October 2026 schedule with realistic shifts & leaves
function generateInitialDutySchedule(): Record<string, Record<string, any>> {
  const assignments: Record<string, Record<string, any>> = {};

  MASTER_EMPLOYEES.forEach((emp) => {
    assignments[emp.id] = {};
    for (let day = 1; day <= 31; day++) {
      const dateStr = `2026-10-${day.toString().padStart(2, '0')}`;
      const dayOfWeek = (day + 3) % 7; // Approx day of week (0=Sun, 6=Sat)

      // Cuti rule for Putu Dewi (5 to 7 Oct)
      if (emp.id === 'emp-tek-16' && day >= 5 && day <= 7) {
        assignments[emp.id][dateStr] = { availability: 'CT', reason: 'Cuti Tahunan', primaryCode: '' };
        continue;
      }

      // Weekend = Libur for some staff
      if (dayOfWeek === 0 || dayOfWeek === 6) {
        if (day % 2 === 0) {
          assignments[emp.id][dateStr] = { availability: 'L', reason: 'Lepas Piket Akhir Pekan', primaryCode: '' };
          continue;
        }
      }

      // Sample allowed double duty on Komang Arta (6 Oct)
      if (emp.id === 'emp-tek-15' && day === 6) {
        assignments[emp.id][dateStr] = {
          primaryCode: 'OB/TDM',
          secondaryCode: 'TDM',
          hasWarning: true,
          warningMessage: 'Rangkap OB Van dan TDM siaran sore (OB/TDM) diizinkan untuk operasional studio luar.',
        };
        continue;
      }

      // Sample rest period warning on Komang Arta (7 Oct after late duty 6 Oct)
      if (emp.id === 'emp-tek-15' && day === 7) {
        assignments[emp.id][dateStr] = {
          primaryCode: 'TDP',
          hasWarning: true,
          warningMessage: 'Jeda istirahat Komang Arta hanya 4 jam setelah TDM kemarin.',
        };
        continue;
      }

      // Assign primary job code based on qualifications
      if (emp.jobCodes.length > 0) {
        // Alternate between morning and evening shifts
        const codeIndex = (day + emp.name.length) % emp.jobCodes.length;
        const code = emp.jobCodes[codeIndex];
        assignments[emp.id][dateStr] = { primaryCode: code };
      } else {
        assignments[emp.id][dateStr] = { primaryCode: 'U' };
      }
    }
  });

  return assignments;
}

